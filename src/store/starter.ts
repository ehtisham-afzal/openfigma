export function solidFill(color: string, variableId?: string | null, opacity = 1): FillLayer {
  return {
    id: `fill-${Math.random().toString(36).slice(2, 8)}`,
    type: "solid",
    visible: true,
    opacity,
    color,
    variableId: variableId ?? null,
  }
}

function makeNode(
  partial: Partial<DesignNode> & Pick<DesignNode, "id" | "name" | "type">
): DesignNode {
  return {
    parentId: null,
    x: 0,
    y: 0,
    width: 120,
    height: 80,
    rotation: 0,
    opacity: 1,
    visible: true,
    locked: false,
    fills: [solidFill("#0d99ff")],
    strokes: [],
    effects: [],
    cornerRadius: 0,
    blendMode: "normal",
    ...partial,
  }
}

